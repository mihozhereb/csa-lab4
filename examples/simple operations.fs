: ARITHMETIC
    2 3 +          \ 2 + 3 = 5, DS: [5]
    push_flags     \ флаги результата 5: NZVC = 0000, DS: [5, 0]
    drop           \ удалить флаги, DS: [5]
    drop           \ удалить результат, DS: []

    10 14 -        \ 10 - 14 = -4, DS: [-4]
    push_flags     \ результат отрицательный: N=1, происходит заем: C=1, NZVC = 1001, DS: [-4, 9]
    drop           \ удалить флаги, DS: [-4]
    drop           \ удалить результат, DS: []

    6 7 *          \ 6 * 7 = 42, DS: [42]
    drop           \ удалить результат, DS: []

    20 5 /         \ 20 / 5 = 4, DS: [4]
    drop           \ удалить результат, DS: []
;

: BITWISE
    6 3 &          \ 6 = 0110, 3 = 0011
                   \ 0110 & 0011 = 0010 = 2, DS: [2]
    drop           \ DS: []

    6 3 |          \ 6 = 0110, 3 = 0011
                   \ 0110 | 0011 = 0111 = 7, DS: [7]
    drop           \ DS: []

    6 3 ^          \ 6 = 0110, 3 = 0011
                   \ 0110 ^ 0011 = 0101 = 5, DS: [5]
    drop           \ DS: []

    0 ~            \ ~0 = -1, потому что все 32 бита становятся 1
                   \ 0000...0000 -> 1111...1111 = -1, DS: [-1]
    drop           \ DS: []
;

: STACK_OPS
    1 2 3          \ DS: [1, 2, 3]

    dup            \ продублировать вершину, DS: [1, 2, 3, 3]
    drop           \ удалить верхний элемент, DS: [1, 2, 3]

    swap           \ поменять два верхних элемента, DS: [1, 3, 2]
    over           \ скопировать второй элемент сверху, DS: [1, 3, 2, 3]

    drop           \ удалить 3, DS: [1, 3, 2]
    drop           \ удалить 2, DS: [1, 3]
    drop           \ удалить 3, DS: [1]
;

